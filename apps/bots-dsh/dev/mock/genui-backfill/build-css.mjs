// Writes mock.css: the Bot team's own sheets, so the mock wears the real surface.
//
//   node dev/mock/genui-backfill/build-css.mjs
//
// The file is generated and not committed: it is a snapshot of this checkout's client styles,
// and it goes stale as soon as styles.js or genui.js changes. The clay art atlases are left
// out of it (about 900 KB of data URLs): this mock draws no pet and no clay figure.
//
// Only the sheets are wanted, but they are exported by modules that also import React and the
// desktop's interface primitives. Every bare package is aliased to one stub that answers any
// property with a callable, so the graph links without a DOM; nothing calls it while a sheet is
// built.
import { build } from 'esbuild'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const client = resolve(here, '../../..', 'src/client')
const out = join(here, 'mock.css')
const scratch = mkdtempSync(join(tmpdir(), 'genui-backfill-mock-'))
const at = name => join(client, name)

const stub = join(scratch, 'stub.js')
// Every name the client modules import from a bare package, answered with a harmless value:
// nothing here runs while a sheet is built.
writeFileSync(stub, [
  'export class Component {}',
  'export const Fragment = null',
  'export const createElement = () => null',
  'export const createPortal = () => null',
  'export const isValidElement = () => false',
  'export const startTransition = fn => fn()',
  'export const useCallback = fn => fn',
  'export const useEffect = () => undefined',
  'export const useId = () => "mock"',
  'export const useLayoutEffect = () => undefined',
  'export const useMemo = fn => fn()',
  'export const useRef = value => ({ current: value ?? null })',
  'export const useState = value => [typeof value === "function" ? value() : value, () => {}]',
  'export const useSyncExternalStore = (subscribe, read) => read()',
  'export const FishLogo = null',
  'export const MarkdownText = null',
  'export const writeClipboard = async () => {}',
  'export const WidgetCard = null',
  'export const ViewUi = null',
  'export const DEEP_VIEW_CSS = ""',
  'export const WidgetView = null',
  'export const CoreWidgetView = null',
  'export const ViewMenuList = null',
  'export const CoreViewMenuList = null',
  'export const checkShownView = () => ({ ok: true })',
  'const qrcode = () => ({ addData() {}, make() {}, createImgTag: () => "" })',
  'export default qrcode',
].join('\n'))

const bare = {
  name: 'stub-bare',
  setup(b) {
    b.onResolve({ filter: /^[A-Za-z@]/ }, () => ({ path: stub }))
  },
}

const entry = join(scratch, 'entry.js')
writeFileSync(entry, [
  `export { SHELL_CSS } from '${at('styles.js')}'`,
  `export { GENUI_CSS } from '${at('genui.js')}'`,
  `export { allThemes, themeCss } from '${at('themes.js')}'`,
].join('\n'))
const bundle = join(scratch, 'bundle.mjs')

try {
  await build({
    entryPoints: [entry], bundle: true, format: 'esm', outfile: bundle,
    absWorkingDir: resolve(here, '../../..'), plugins: [bare], logLevel: 'error',
  })
  const sheets = await import(pathToFileURL(bundle).href)
  const theme = sheets.themeCss(sheets.allThemes().deepseek)
  const css = [theme, sheets.SHELL_CSS, sheets.GENUI_CSS].join('\n')
  const small = css.replace(/url\((['"]?)data:image[\s\S]*?\1\)/g, 'none')
  writeFileSync(out, '/* Generated by dev/mock/genui-backfill/build-css.mjs; do not edit.\n'
    + '   The clay art atlases are left out: the mock draws no pet. */\n' + small)
  console.log(`wrote ${out} (${Math.round(small.length / 1024)} KB)`)
} finally {
  rmSync(scratch, { recursive: true, force: true })
}
