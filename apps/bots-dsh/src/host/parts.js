// Whether a Bot's part has something a handoff note must carry. The team's own setup kickoff
// is not a conversation; anything else a person or another Bot put in the part is: a typed
// message, a question-card or view reply, a bot-to-bot message, a schedule. DSH's own context
// (runtime context, a working-directory notice), an earlier handoff package and the request
// for a handoff note an agent switch sends the outgoing agent are not.
export function saidSomething(messages) {
  return (messages ?? []).some(message => message?.role === 'user'
    && message.source?.handoff !== true
    && message.source?.role !== 'handoff-note'
    && message.source?.role !== 'kickoff'
    && message.source?.kind !== 'runtime-context'
    && message.source?.kind !== 'working-directory')
}

// Source kinds that describe the environment of this part, plus the Bot's own memory recall.
const CROSSING_CONTEXT = new Set([
  'runtime-context', 'working-directory', 'time-context', 'tmux-context', 'agent-instructions',
  'skill-catalog', 'plan-mode', 'ds-bot-time-context', 'ds-bot-memory-recall',
])
// DSH's modelSwitchNotice and the Bot's fallbackNotice share the source kind and form.
// Only DSH's route notice has this text framing. The fallback notice carries turn content.
const MODEL_SWITCH_NOTICE = /^\[model changed: assistant turns above this point were generated by .+; the session continues with .+\]$/s

function saidForCrossing(messages, freshText) {
  return (messages ?? []).some(message => {
    if (message?.role !== 'user') return false
    const { source, content } = message
    if (source?.role === 'handoff-note') return false
    if (source?.handoff !== true && (source?.role === 'kickoff' || CROSSING_CONTEXT.has(source?.kind))) return false
    const block = Array.isArray(content) && content.length === 1 ? content[0] : undefined
    const text = block?.type === 'text' ? block.text : undefined
    // A real fresh opening has one text block. Compare its bytes without trimming or joining.
    if (source?.handoff === true) return text !== freshText
    return !(source?.kind === 'model-selection' && source.form === 'notice' && typeof text === 'string' && MODEL_SWITCH_NOTICE.test(text))
  })
}

// An ask_user card as the user saw it. The user's reply is often just an option label,
// which means nothing without the card. Arguments the tool would refuse (no question,
// options that are not { label } objects) showed no card, so they give no text.
export function cardText(args) {
  let card = args
  if (typeof card === 'string') {
    try { card = JSON.parse(card) } catch { return '' }
  }
  const question = typeof card?.question === 'string' ? card.question.trim() : ''
  const given = Array.isArray(card?.options) ? card.options : []
  if (given.some(option => typeof option?.label !== 'string')) return ''
  const options = given.map(option => option.label.trim()).filter(Boolean)
  if (question === '' || options.length === 0) return ''
  const detail = typeof card.detail === 'string' ? card.detail.trim() : ''
  return `[Question card] ${question}${detail ? ` (${detail})` : ''}\nOptions: ${options.join(' / ')}`
}

